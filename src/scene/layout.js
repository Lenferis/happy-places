/* ============================================================
   scene/layout.js
   Числовые константы, определяющие «тело» альбома: размеры
   страниц, толщину, отступы, глобальный поворот группы.
   Отдельный модуль без зависимостей от THREE — чтобы его
   могли импортировать sheets.js / positions.js / album.js
   без создания циклических зависимостей.
   ============================================================ */

/* ---- Размер одной страницы (в метрах сцены) ---- */
export const PAGE_W = 1.0;
export const PAGE_H = 1.28;

/* ---- Обложка чуть больше страницы ---- */
export const COVER_W = PAGE_W + 0.04;
export const COVER_H = PAGE_H + 0.045;
export const COVER_T = 0.0105;      // толщина обложки

/* ---- Толщина одного листа и стартовые отступы ---- */
export const TH_    = 0.0035;                    // «шаг» между листами
export const BASE_R = COVER_T + 0.003;           // высота нижней стопки справа
export const L_BASE = COVER_T + 0.003;           // высота нижней стопки слева

/* ---- Общий поворот всей группы альбома ---- */
export const ALBUM_YAW = -0.045;

/* ---- Отступы активного и бокового листа ---- */
export const ACT_OFF  = TH_ * 0.55;              // подъём активного листа
export const SIDE_OFF = TH_ * 0.18;              // боковой зазор стопок